/** 문자열 해시 (같은 집은 늘 같은 대사) */
export function hashOf(s: string, salt = 0) {
  let h = 2166136261 ^ salt;
  for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
  return h >>> 0;
}
export const pickAt = <T,>(arr: T[], n: number) => arr[n % arr.length];

